using System.Globalization;
using System.Text;

namespace XiHan.Framework.Cli.Packaging;

/// <summary>
/// 生成 .NET Aspire AppHost 的登记代码：按绑定添加资源，把连接串注入应用的绑定环境变量。
/// </summary>
internal static class AspireGenerator
{
    /// <summary>
    /// 生成 <c>aspire/XiHanAppHost.g.cs</c>。
    /// </summary>
    public static PackOutput Generate(AppManifest manifest)
    {
        ArgumentNullException.ThrowIfNull(manifest);
        var method = "Add" + Identifier(manifest.Name);
        var project = "Projects." + Identifier(manifest.AssemblyName);
        var builder = new StringBuilder();
        builder.Append("// <auto-generated/>\n");
        builder.Append("// 由 xihan pack 从 xihan.app.json 生成：把应用及其绑定登记进 .NET Aspire AppHost。\n");
        builder.Append("// 把本文件放进 AppHost 项目，并在 Program.cs 调用 builder.").Append(method).Append("();\n");
        var packages = manifest.Bindings.Values.Select(static b => b.Type).Distinct(StringComparer.Ordinal).Select(static type => type switch
        {
            "connection:relational" => "Aspire.Hosting.PostgreSQL",
            "cache:distributed" => "Aspire.Hosting.Redis",
            "queue" => "Aspire.Hosting.RabbitMQ",
            _ => null,
        }).Where(static p => p is not null).OrderBy(static p => p, StringComparer.Ordinal).ToList();
        if (packages.Count > 0)
        {
            builder.Append("// 需要的包：").Append(string.Join("、", packages)).Append('\n');
        }

        builder.Append('\n');
        builder.Append("using Aspire.Hosting;\n\n");
        builder.Append("/// <summary>\n/// ").Append(manifest.Name).Append(" 的 Aspire 登记。\n/// </summary>\n");
        builder.Append("public static class XiHanAppHost\n{\n");
        builder.Append("    /// <summary>\n    /// 添加 ").Append(manifest.Name).Append(" 及其绑定的资源。\n    /// </summary>\n");
        builder.Append("    public static IResourceBuilder<ProjectResource> ").Append(method).Append("(this IDistributedApplicationBuilder builder)\n    {\n");
        var references = new List<string>();
        foreach (var (binding, settings) in manifest.Bindings.OrderBy(static b => b.Key, StringComparer.Ordinal))
        {
            var variable = Identifier(binding, lowerFirst: true);
            switch (settings.Type)
            {
                case "connection:relational":
                    builder.Append(CultureInfo.InvariantCulture, $"        var {variable} = builder.AddPostgres(\"{binding}\").AddDatabase(\"{manifest.Name}\");\n");
                    references.Add(variable);
                    break;
                case "cache:distributed":
                    builder.Append(CultureInfo.InvariantCulture, $"        var {variable} = builder.AddRedis(\"{binding}\");\n");
                    references.Add(variable);
                    break;
                case "queue":
                    builder.Append(CultureInfo.InvariantCulture, $"        var {variable} = builder.AddRabbitMQ(\"{binding}\");\n");
                    references.Add(variable);
                    break;
                default:
                    builder.Append(CultureInfo.InvariantCulture, $"        var {variable} = builder.AddContainer(\"{binding}\", \"minio/minio\").WithArgs(\"server\", \"/data\").WithHttpEndpoint(port: 9000, targetPort: 9000, name: \"api\");\n");
                    break;
            }
        }

        builder.Append(CultureInfo.InvariantCulture, $"        var app = builder.AddProject<{project}>(\"{manifest.Name}\")\n");
        builder.Append(CultureInfo.InvariantCulture, $"            .WithHttpEndpoint(port: {manifest.Ports.Http}, name: \"http\")\n");
        if (manifest.Ports.Grpc is { } grpc)
        {
            builder.Append(CultureInfo.InvariantCulture, $"            .WithEndpoint(port: {grpc}, scheme: \"http\", name: \"grpc\")\n");
        }

        if (manifest.Scaling is { } scaling)
        {
            builder.Append(CultureInfo.InvariantCulture, $"            .WithReplicas({scaling.Min})\n");
        }
        else if (manifest.Replicas > 1)
        {
            builder.Append(CultureInfo.InvariantCulture, $"            .WithReplicas({manifest.Replicas})\n");
        }

        foreach (var (binding, settings) in manifest.Bindings.OrderBy(static b => b.Key, StringComparer.Ordinal))
        {
            var variable = Identifier(binding, lowerFirst: true);
            builder.Append(CultureInfo.InvariantCulture, $"            .WithEnvironment(\"XiHan__Bindings__{binding}__type\", \"{settings.Type}\")\n");
            builder.Append(settings.Type == "blob"
                ? $"            .WithEnvironment(\"XiHan__Bindings__{binding}__value\", {variable}.GetEndpoint(\"api\"))\n"
                : $"            .WithEnvironment(\"XiHan__Bindings__{binding}__value\", {variable})\n");
            if (references.Contains(variable))
            {
                builder.Append(CultureInfo.InvariantCulture, $"            .WithReference({variable})\n");
            }
        }

        foreach (var (key, value) in manifest.Environment.OrderBy(static e => e.Key, StringComparer.Ordinal))
        {
            builder.Append(CultureInfo.InvariantCulture, $"            .WithEnvironment(\"{key}\", \"{value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal)}\")\n");
        }

        builder.Append("            ;\n        return app;\n    }\n}\n");
        return new PackOutput("aspire/XiHanAppHost.g.cs", builder.ToString());
    }

    /// <summary>
    /// 把名字变成 C# 标识符：按 <c>-</c> 分段首字母大写。
    /// </summary>
    private static string Identifier(string name, bool lowerFirst = false)
    {
        var parts = name.Split(['-', '.', '_'], StringSplitOptions.RemoveEmptyEntries)
            .Select(static p => char.ToUpperInvariant(p[0]) + p[1..]);
        var identifier = string.Concat(parts);
        if (identifier.Length == 0 || char.IsDigit(identifier[0]))
        {
            identifier = "_" + identifier;
        }

        return lowerFirst ? char.ToLowerInvariant(identifier[0]) + identifier[1..] : identifier;
    }
}
