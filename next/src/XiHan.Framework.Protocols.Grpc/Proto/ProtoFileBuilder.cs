using System.Globalization;
using System.Text;
using XiHan.Framework.Primitives;
using XiHan.Framework.Protocols.Grpc.Methods;

namespace XiHan.Framework.Protocols.Grpc.Proto;

/// <summary>
/// 从 gRPC 操作表生成 <c>.proto</c>（proto3）文本：每个消息描述一个 <c>message</c>，每个资源一个 <c>service</c>，每个操作一个一元 <c>rpc</c>。
/// 字段名按 JSON 名转 lower_snake_case，proto 默认的 <c>json_name</c> 与 JSON 名不同时写 <c>[json_name = "…"]</c>。同名消息在不同操作里形状必须一致。
/// </summary>
[ApiLevel(Stability.Preview, "5.0")]
public static class ProtoFileBuilder
{
    /// <summary>
    /// 生成 <c>.proto</c> 文本。
    /// </summary>
    public static string Build(IReadOnlyList<GrpcOperation> operations, string? package)
    {
        ArgumentNullException.ThrowIfNull(operations);
        var messages = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var operation in operations)
        {
            Collect(operation.Request, messages);
            Collect(operation.Response, messages);
        }

        var builder = new StringBuilder();
        builder.Append("// Generated by XiHan Framework from operation contracts; the server derives it from the same schemas at runtime.\n");
        builder.Append("syntax = \"proto3\";\n\n");
        if (!string.IsNullOrEmpty(package))
        {
            builder.Append("package ").Append(package).Append(";\n\n");
        }

        foreach (var message in messages.Values)
        {
            builder.Append(message).Append('\n');
        }

        foreach (var service in operations.GroupBy(static o => o.Method.Service, StringComparer.Ordinal).OrderBy(static g => g.Key, StringComparer.Ordinal))
        {
            builder.Append("service ").Append(service.Key).Append(" {\n");
            foreach (var operation in service.OrderBy(static o => o.Method.Method, StringComparer.Ordinal))
            {
                builder.Append("  // ").Append(operation.Descriptor.Id).Append('\n');
                builder.Append("  rpc ").Append(operation.Method.Method).Append(" (").Append(operation.Request.Name).Append(") returns (").Append(operation.Response.Name).Append(");\n");
            }

            builder.Append("}\n\n");
        }

        return builder.ToString().TrimEnd('\n') + "\n";
    }

    /// <summary>
    /// 一个消息的 <c>message</c> 块。
    /// </summary>
    public static string Render(ProtoMessage message)
    {
        ArgumentNullException.ThrowIfNull(message);
        var builder = new StringBuilder();
        builder.Append("message ").Append(message.Name).Append(" {\n");
        foreach (var field in message.Fields)
        {
            var name = ProtoFieldName(field.JsonName);
            builder.Append("  ");
            switch (field.Cardinality)
            {
                case ProtoCardinality.Optional:
                    builder.Append("optional ").Append(TypeName(field.Value));
                    break;
                case ProtoCardinality.Repeated:
                    builder.Append("repeated ").Append(TypeName(field.Value));
                    break;
                case ProtoCardinality.Map:
                    builder.Append("map<string, ").Append(TypeName(field.Value)).Append('>');
                    break;
                default:
                    builder.Append(TypeName(field.Value));
                    break;
            }

            builder.Append(' ').Append(name).Append(" = ").Append(field.Number.ToString(CultureInfo.InvariantCulture));
            // proto 按 lowerCamel(snake_name) 推导 json_name；与真实 JSON 名不同时显式写出
            if (!string.Equals(DefaultJsonName(name), field.JsonName, StringComparison.Ordinal))
            {
                builder.Append(" [json_name = \"").Append(field.JsonName).Append("\"]");
            }

            builder.Append(";\n");
        }

        builder.Append("}\n");
        return builder.ToString();
    }

    /// <summary>
    /// JSON 名转 proto 字段名：大写字母前加下划线并小写，非标识符字符换成下划线，数字开头加下划线。
    /// </summary>
    public static string ProtoFieldName(string jsonName)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(jsonName);
        var builder = new StringBuilder(jsonName.Length + 4);
        for (var index = 0; index < jsonName.Length; index++)
        {
            var character = jsonName[index];
            if (char.IsAsciiLetterUpper(character))
            {
                if (index > 0 && jsonName[index - 1] != '_')
                {
                    builder.Append('_');
                }

                builder.Append(char.ToLowerInvariant(character));
            }
            else if (char.IsAsciiLetterOrDigit(character) || character == '_')
            {
                builder.Append(character);
            }
            else
            {
                builder.Append('_');
            }
        }

        if (char.IsAsciiDigit(builder[0]))
        {
            builder.Insert(0, '_');
        }

        return builder.ToString();
    }

    /// <summary>
    /// 递归收集消息文本；同名消息形状不同即冲突。
    /// </summary>
    private static void Collect(ProtoMessage message, SortedDictionary<string, string> messages)
    {
        var rendered = Render(message);
        if (messages.TryGetValue(message.Name, out var existing))
        {
            if (!string.Equals(existing, rendered, StringComparison.Ordinal))
            {
                throw new FrameworkException(GrpcErrors.MessageConflict, $"protobuf message '{message.Name}' is defined with different fields by different operations; rename one of the types.");
            }

            return;
        }

        messages.Add(message.Name, rendered);
        foreach (var field in message.Fields)
        {
            if (field.Value.Message is { } nested)
            {
                Collect(nested, messages);
            }
        }
    }

    /// <summary>
    /// 值类型在 <c>.proto</c> 里的名字。
    /// </summary>
    private static string TypeName(ProtoValueType type) => type.Kind switch
    {
        ProtoKind.Text or ProtoKind.TextNumber or ProtoKind.Json => "string",
        ProtoKind.Bytes => "bytes",
        ProtoKind.Bool => "bool",
        ProtoKind.Varint32 => "int32",
        ProtoKind.Varint64 => "int64",
        ProtoKind.Fixed32 => "float",
        ProtoKind.Fixed64 => "double",
        ProtoKind.Message => type.Message!.Name,
        _ => throw new InvalidOperationException($"Unknown proto kind '{type.Kind}'."),
    };

    /// <summary>
    /// proto 对字段名默认推导的 <c>json_name</c>：去掉下划线，其后的字母大写。
    /// </summary>
    private static string DefaultJsonName(string protoName)
    {
        var builder = new StringBuilder(protoName.Length);
        var upper = false;
        foreach (var character in protoName)
        {
            if (character == '_')
            {
                upper = true;
                continue;
            }

            builder.Append(upper ? char.ToUpperInvariant(character) : character);
            upper = false;
        }

        return builder.ToString();
    }
}
